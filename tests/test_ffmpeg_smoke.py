"""
Smoke tests that drive a REAL FFmpeg build through yt-dlp's own postprocessors.

Every other test mocks FFmpeg, so a green suite says nothing about a new binary.
These run only when ``MEADOWLARK_FFMPEG_DIR`` points at a directory holding
``ffmpeg.exe`` and ``ffprobe.exe`` (see ``scripts/ffmpeg_pin.py fetch``); the monthly
``ffmpeg-bump`` workflow sets it for the candidate build. Unset means skipped. Set but
missing means FAIL, so a typo cannot skip silently in CI.

yt-dlp builds each command line itself and parses ``ffmpeg -version`` to detect
features, so the postprocessor classes are called directly (not ``ffmpeg`` with
hand-written arguments). That catches a version string yt-dlp cannot parse, a codec
missing from the build (``libmp3lame``, ``libopus``, ``libvpx``) and a merge or remux
that regresses. Input media is generated by the candidate itself from ``lavfi`` sources.

Covered, for every format the Settings dialog offers: merge, remux, audio extraction.
Not covered: SponsorBlock cutting (``ModifyChapters``) also calls FFmpeg, but it needs
a segments-annotated info dict that is expensive to fake.
"""

import json
import os
import shutil
import subprocess
from pathlib import Path
from typing import Any, cast

import pytest
from yt_dlp import YoutubeDL
from yt_dlp.postprocessor.ffmpeg import (
    FFmpegExtractAudioPP,
    FFmpegMergerPP,
    FFmpegPostProcessor,
    FFmpegVideoRemuxerPP,
)

from src.settings_dialog import AUDIO_FORMAT_OPTIONS, VIDEO_FORMAT_OPTIONS
from src.ydl_options import build_shared_extraction_opts

_ENV_VAR = "MEADOWLARK_FFMPEG_DIR"

pytestmark = [
    pytest.mark.ffmpeg_smoke,
    pytest.mark.skipif(_ENV_VAR not in os.environ, reason=f"{_ENV_VAR} is not set"),
]

_VIDEO_FORMATS = [fmt for fmt, _ in VIDEO_FORMAT_OPTIONS]
_AUDIO_FORMATS = [fmt for fmt, _ in AUDIO_FORMAT_OPTIONS]

# Codec ffprobe reports for the sole stream of each extracted audio format.
_EXPECTED_CODEC = {
    "m4a": "aac",
    "mp3": "mp3",
    "opus": "opus",
    "flac": "flac",
    "wav": "pcm_s16le",
}

# Remux input per target format: a file in a DIFFERENT container with compatible codecs.
_REMUX_SOURCE = {"mp4": "h264.mkv", "mkv": "h264.mp4", "webm": "vp9.mkv"}

_CLIP_SECONDS = "2"
_FFMPEG_TIMEOUT_S = 120


@pytest.fixture(scope="session")
def ffmpeg_dir() -> Path:
    directory = Path(os.environ[_ENV_VAR])
    assert directory.is_dir(), f"{_ENV_VAR}={directory} is not a directory"
    for exe in ("ffmpeg.exe", "ffprobe.exe"):
        assert (directory / exe).is_file(), f"{directory} has no {exe}"
    return directory


@pytest.fixture(scope="session")
def ydl(ffmpeg_dir: Path) -> YoutubeDL:
    # yt-dlp types its params as a closed TypedDict; the shared opts are a plain dict.
    params = {**build_shared_extraction_opts(), "ffmpeg_location": str(ffmpeg_dir), "quiet": True}
    return YoutubeDL(cast("Any", params))


def _ffmpeg(ffmpeg_dir: Path, *args: str) -> None:
    subprocess.run(  # noqa: S603 -- our own candidate binary, fixed arguments
        [str(ffmpeg_dir / "ffmpeg.exe"), "-v", "error", "-y", *args],
        check=True,
        timeout=_FFMPEG_TIMEOUT_S,
    )


def _probe(ffmpeg_dir: Path, path: Path) -> list[dict[str, Any]]:
    out = subprocess.run(  # noqa: S603 -- our own candidate binary, fixed arguments
        [
            str(ffmpeg_dir / "ffprobe.exe"),
            "-v",
            "error",
            "-show_streams",
            "-of",
            "json",
            str(path),
        ],
        check=True,
        capture_output=True,
        text=True,
        timeout=_FFMPEG_TIMEOUT_S,
    )
    return json.loads(out.stdout)["streams"]


@pytest.fixture(scope="session")
def media(ffmpeg_dir: Path, tmp_path_factory: pytest.TempPathFactory) -> Path:
    """Generate tiny inputs with the candidate: separate video/audio plus muxed variants."""
    root = tmp_path_factory.mktemp("media")
    video = f"testsrc=duration={_CLIP_SECONDS}:size=160x120:rate=15"
    audio = f"sine=duration={_CLIP_SECONDS}:frequency=440"
    vp9 = ["-c:v", "libvpx-vp9", "-deadline", "realtime", "-cpu-used", "8", "-b:v", "100k"]
    _ffmpeg(ffmpeg_dir, "-f", "lavfi", "-i", video, "-c:v", "libx264", str(root / "v.mp4"))
    _ffmpeg(ffmpeg_dir, "-f", "lavfi", "-i", audio, "-c:a", "aac", str(root / "a.m4a"))
    _ffmpeg(ffmpeg_dir, "-f", "lavfi", "-i", video, *vp9, str(root / "v.webm"))
    _ffmpeg(ffmpeg_dir, "-f", "lavfi", "-i", audio, "-c:a", "libopus", str(root / "a.webm"))
    # Muxed files for the remux and extract-audio cases (stream copy only).
    for name in ("h264.mp4", "h264.mkv"):
        _ffmpeg(
            ffmpeg_dir,
            "-i",
            str(root / "v.mp4"),
            "-i",
            str(root / "a.m4a"),
            "-c",
            "copy",
            str(root / name),
        )
    _ffmpeg(
        ffmpeg_dir,
        "-i",
        str(root / "v.webm"),
        "-i",
        str(root / "a.webm"),
        "-c",
        "copy",
        str(root / "vp9.mkv"),
    )
    return root


def _kinds(streams: list[dict[str, Any]]) -> list[str]:
    return sorted(s["codec_type"] for s in streams)


def _requested_format(path: Path, kind: str) -> dict[str, Any]:
    return {
        "filepath": str(path),
        "protocol": "https",
        "vcodec": "avc1" if kind == "video" else "none",
        "acodec": "none" if kind == "video" else "mp4a",
    }


def test_yt_dlp_detects_ffmpeg_and_ffprobe(ydl: YoutubeDL) -> None:
    pp = FFmpegPostProcessor(ydl)
    versions = cast("dict[str, Any]", FFmpegPostProcessor.get_versions(ydl))
    assert pp.available, "yt-dlp does not recognise the candidate ffmpeg"
    assert pp.probe_available, "yt-dlp does not recognise the candidate ffprobe"
    assert versions.get("ffmpeg"), f"yt-dlp could not parse the ffmpeg version: {versions}"


@pytest.mark.parametrize("vfmt", _VIDEO_FORMATS)
def test_merge(vfmt: str, ydl: YoutubeDL, ffmpeg_dir: Path, media: Path, tmp_path: Path) -> None:
    video, audio = ("v.webm", "a.webm") if vfmt == "webm" else ("v.mp4", "a.m4a")
    files = [tmp_path / video, tmp_path / audio]
    for src in (video, audio):
        shutil.copy(media / src, tmp_path / src)
    out = tmp_path / f"merged.{vfmt}"
    info = {
        "filepath": str(out),
        "requested_formats": [
            _requested_format(files[0], "video"),
            _requested_format(files[1], "audio"),
        ],
        "__files_to_merge": [str(f) for f in files],
    }
    FFmpegMergerPP(ydl).run(info)
    assert out.is_file()
    assert _kinds(_probe(ffmpeg_dir, out)) == ["audio", "video"]


@pytest.mark.parametrize("vfmt", _VIDEO_FORMATS)
def test_remux(vfmt: str, ydl: YoutubeDL, ffmpeg_dir: Path, media: Path, tmp_path: Path) -> None:
    assert vfmt in _REMUX_SOURCE, f"add {vfmt} to _REMUX_SOURCE"
    source = tmp_path / _REMUX_SOURCE[vfmt]
    shutil.copy(media / source.name, source)
    info = {"filepath": str(source), "ext": source.suffix.lstrip(".")}
    _, result = FFmpegVideoRemuxerPP(ydl, preferedformat=vfmt).run(info)
    out = Path(result["filepath"])
    assert out.suffix == f".{vfmt}"
    assert out.is_file()
    assert _kinds(_probe(ffmpeg_dir, out)) == ["audio", "video"]


@pytest.mark.parametrize("afmt", _AUDIO_FORMATS)
def test_extract_audio(
    afmt: str, ydl: YoutubeDL, ffmpeg_dir: Path, media: Path, tmp_path: Path
) -> None:
    assert afmt in _EXPECTED_CODEC, f"add {afmt} to _EXPECTED_CODEC"
    source = tmp_path / "h264.mp4"
    shutil.copy(media / source.name, source)
    info = {"filepath": str(source), "ext": "mp4"}
    _, result = FFmpegExtractAudioPP(ydl, preferredcodec=afmt).run(info)
    out = Path(result["filepath"])
    assert out.is_file()
    streams = _probe(ffmpeg_dir, out)
    assert [s["codec_name"] for s in streams] == [_EXPECTED_CODEC[afmt]]
